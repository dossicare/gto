-- Support Knowledge: schema, row-level security, admin write functions and public views.
-- Safe to re-run. Apply in the Supabase SQL editor (or `supabase db push`).
--
-- Access model
--   * Visitors (anon) can read ONLY the three public_* views. Base tables are closed to them.
--   * The single administrator (a row in admin_users) can read everything and writes through
--     the admin_* functions below, which keep revision history immutable.
--   * The service-role key (used only by the one-off import script) bypasses RLS.

-- ---------------------------------------------------------------------------------------------
-- Administrator allow-list
-- ---------------------------------------------------------------------------------------------
create table if not exists public.admin_users (
  user_id    uuid primary key references auth.users (id) on delete cascade,
  created_at timestamptz not null default now()
);
alter table public.admin_users enable row level security;

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (select 1 from public.admin_users where user_id = (select auth.uid()));
$$;

-- ---------------------------------------------------------------------------------------------
-- Offers (current record + immutable revision history)
-- ---------------------------------------------------------------------------------------------
create table if not exists public.offers (
  offer_id   text primary key,
  revision   integer     not null check (revision >= 1),
  payload    jsonb       not null check (jsonb_typeof(payload) = 'object'),
  updated_at timestamptz not null default now()
);
create unique index if not exists offers_offer_id_lower_key on public.offers (lower(offer_id));

create table if not exists public.offer_versions (
  offer_id text        not null,
  revision integer     not null check (revision >= 1),
  payload  jsonb       not null check (jsonb_typeof(payload) = 'object'),
  saved_at timestamptz not null default now(),
  action   text        not null default 'save',
  primary key (offer_id, revision)
);

create table if not exists public.offer_documents (
  document_id    bigint generated by default as identity primary key,
  offer_id       text        not null,
  filename       text        not null,
  media_type     text        not null,
  source_version text        not null default 'Not stated',
  sha256         text        not null,
  size           integer     not null,
  approved       boolean     not null default false,
  uploaded_at    timestamptz not null default now(),
  storage_path   text
);

create table if not exists public.offer_import_batches (digest text primary key);
create table if not exists public.offer_migrations (name text primary key, completed_at text not null);

-- ---------------------------------------------------------------------------------------------
-- GTO templates (bilingual script library)
-- ---------------------------------------------------------------------------------------------
create table if not exists public.gto_templates (
  template_id text        primary key,
  revision    integer     not null check (revision >= 1),
  payload     jsonb       not null check (jsonb_typeof(payload) = 'object'),
  deleted     boolean     not null default false,
  updated_at  timestamptz not null default now()
);

create table if not exists public.gto_template_history (
  template_id text        not null,
  revision    integer     not null check (revision >= 1),
  payload     jsonb       not null check (jsonb_typeof(payload) = 'object'),
  saved_at    timestamptz not null default now(),
  action      text        not null default 'save',
  primary key (template_id, revision)
);

-- ---------------------------------------------------------------------------------------------
-- Original uploaded source documents (binary content lives in the private Storage bucket)
-- ---------------------------------------------------------------------------------------------
create table if not exists public.source_documents (
  id           bigint generated by default as identity primary key,
  origin       text        not null check (origin in ('gto_template_sources', 'operation_documents')),
  legacy_id    bigint,
  filename     text        not null,
  version      text        not null default '',
  media_type   text        not null,
  sha256       text        not null unique,
  size         integer     not null,
  storage_path text,
  created_at   timestamptz not null default now()
);

-- ---------------------------------------------------------------------------------------------
-- General Terms & Conditions snapshots
-- ---------------------------------------------------------------------------------------------
create table if not exists public.official_terms_snapshots (
  revision   integer     primary key check (revision >= 1),
  source_url text        not null,
  fetched_at timestamptz not null,
  sha256     text        not null,
  html       text        not null
);

-- ---------------------------------------------------------------------------------------------
-- Retained data from sections that are no longer in the interface (admin-only, never public)
-- ---------------------------------------------------------------------------------------------
create table if not exists public.operation_items (
  record_id text    primary key,
  revision  integer not null check (revision >= 1),
  payload   jsonb   not null check (jsonb_typeof(payload) = 'object')
);
create table if not exists public.operation_versions (
  record_id text    not null,
  revision  integer not null check (revision >= 1),
  payload   jsonb   not null check (jsonb_typeof(payload) = 'object'),
  action    text    not null default 'save',
  primary key (record_id, revision)
);
create table if not exists public.operation_imports (import_key text primary key);

create table if not exists public.legacy_records (
  db            text    not null check (db in ('offers', 'operations')),
  id            integer not null,
  section       text,
  title         text,
  category      text,
  keywords      text,
  content       text,
  source        text,
  version       text,
  status        text,
  review_due    text,
  fictional     integer,
  updated_at    text,
  source_type   text,
  captured_at   text,
  source_locator text,
  source_hash   text,
  primary key (db, id)
);
create table if not exists public.legacy_audit (
  db        text    not null check (db in ('offers', 'operations')),
  id        integer not null,
  record_id integer,
  action    text,
  timestamp text,
  primary key (db, id)
);

-- ---------------------------------------------------------------------------------------------
-- Row-level security: every table is closed; only the administrator gets policies.
-- ---------------------------------------------------------------------------------------------
alter table public.offers                   enable row level security;
alter table public.offer_versions           enable row level security;
alter table public.offer_documents          enable row level security;
alter table public.offer_import_batches     enable row level security;
alter table public.offer_migrations         enable row level security;
alter table public.gto_templates            enable row level security;
alter table public.gto_template_history     enable row level security;
alter table public.source_documents         enable row level security;
alter table public.official_terms_snapshots enable row level security;
alter table public.operation_items          enable row level security;
alter table public.operation_versions       enable row level security;
alter table public.operation_imports        enable row level security;
alter table public.legacy_records           enable row level security;
alter table public.legacy_audit             enable row level security;

-- An administrator may see their own allow-list row (the app never needs more than that).
drop policy if exists admin_users_self on public.admin_users;
create policy admin_users_self on public.admin_users
  for select to authenticated using (user_id = (select auth.uid()));

-- Read access for the administrator on every table.
do $$
declare t text;
begin
  foreach t in array array[
    'offers','offer_versions','offer_documents','offer_import_batches','offer_migrations',
    'gto_templates','gto_template_history','source_documents','official_terms_snapshots',
    'operation_items','operation_versions','operation_imports','legacy_records','legacy_audit']
  loop
    execute format('drop policy if exists admin_read on public.%I', t);
    execute format('create policy admin_read on public.%I for select to authenticated using (public.is_admin())', t);
  end loop;
end $$;

-- Offers, templates and their histories are written ONLY through the functions below
-- (so history stays immutable and edits are checked against the expected revision).
-- General-terms snapshots may additionally be deleted by the administrator.
drop policy if exists admin_delete on public.official_terms_snapshots;
create policy admin_delete on public.official_terms_snapshots
  for delete to authenticated using (public.is_admin());

-- ---------------------------------------------------------------------------------------------
-- Administrator write functions (security definer, always re-check is_admin())
-- ---------------------------------------------------------------------------------------------
create or replace function public.admin_save_offer(
  p_payload  jsonb,
  p_expected integer default null,
  p_action   text    default 'save')
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_id          text;
  v_current_id  text;
  v_current_rev integer;
  v_rev         integer;
  v_payload     jsonb;
  v_stamp       timestamptz := now();
begin
  if not public.is_admin() then
    raise exception 'Administrator access is required.' using errcode = '42501';
  end if;
  if p_payload is null or jsonb_typeof(p_payload) <> 'object' then
    raise exception 'Offer payload must be a JSON object.' using errcode = '22023';
  end if;
  v_id := btrim(coalesce(p_payload ->> 'offer_id', ''));
  if v_id = '' then
    raise exception 'offer_id is required.' using errcode = '22023';
  end if;

  select o.offer_id, o.revision into v_current_id, v_current_rev
    from public.offers o where lower(o.offer_id) = lower(v_id) for update;

  if found then
    if p_expected is null then
      raise exception 'Offer ID already exists. Open it in the editor to create a new revision.' using errcode = '23505';
    end if;
    if v_current_rev <> p_expected then
      raise exception 'This offer changed in another session. Reload before saving.' using errcode = '40001';
    end if;
    v_id  := v_current_id;
    v_rev := v_current_rev + 1;
  else
    if p_expected is not null then
      raise exception 'This offer changed in another session. Reload before saving.' using errcode = '40001';
    end if;
    v_rev := 1;
  end if;

  v_payload := p_payload || jsonb_build_object(
    'offer_id', v_id,
    'revision', v_rev,
    'updated_at', to_char(v_stamp at time zone 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.US"+00:00"'));

  insert into public.offer_versions (offer_id, revision, payload, saved_at, action)
    values (v_id, v_rev, v_payload, v_stamp, coalesce(nullif(btrim(p_action), ''), 'save'));
  insert into public.offers (offer_id, revision, payload, updated_at)
    values (v_id, v_rev, v_payload, v_stamp)
    on conflict (offer_id) do update
      set revision = excluded.revision, payload = excluded.payload, updated_at = excluded.updated_at;
  return v_payload;
end;
$$;

create or replace function public.admin_save_template(
  p_payload  jsonb,
  p_expected integer default null,
  p_action   text    default 'save')
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_id          text;
  v_current_rev integer;
  v_rev         integer;
  v_payload     jsonb;
  v_stamp       timestamptz := now();
begin
  if not public.is_admin() then
    raise exception 'Administrator access is required.' using errcode = '42501';
  end if;
  if p_payload is null or jsonb_typeof(p_payload) <> 'object' then
    raise exception 'Template payload must be a JSON object.' using errcode = '22023';
  end if;
  v_id := btrim(coalesce(p_payload ->> 'template_id', ''));
  if v_id = '' then
    raise exception 'template_id is required.' using errcode = '22023';
  end if;

  select t.revision into v_current_rev from public.gto_templates t where t.template_id = v_id for update;
  if found then
    if p_expected is null then
      raise exception 'Template ID already exists.' using errcode = '23505';
    end if;
    if v_current_rev <> p_expected then
      raise exception 'This template changed in another session. Reload before saving.' using errcode = '40001';
    end if;
    v_rev := v_current_rev + 1;
  else
    if p_expected is not null then
      raise exception 'This template changed in another session. Reload before saving.' using errcode = '40001';
    end if;
    v_rev := 1;
  end if;

  v_payload := p_payload || jsonb_build_object('template_id', v_id, 'revision', v_rev);

  insert into public.gto_template_history (template_id, revision, payload, saved_at, action)
    values (v_id, v_rev, v_payload, v_stamp, coalesce(nullif(btrim(p_action), ''), 'save'));
  insert into public.gto_templates (template_id, revision, payload, deleted, updated_at)
    values (v_id, v_rev, v_payload, coalesce((v_payload ->> 'deleted')::boolean, false), v_stamp)
    on conflict (template_id) do update
      set revision = excluded.revision, payload = excluded.payload,
          deleted = excluded.deleted, updated_at = excluded.updated_at;
  return v_payload;
end;
$$;

create or replace function public.admin_add_terms_snapshot(p_html text, p_source_url text)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_digest     text;
  v_prior_rev  integer;
  v_prior_hash text;
  v_rev        integer;
begin
  if not public.is_admin() then
    raise exception 'Administrator access is required.' using errcode = '42501';
  end if;
  if p_html is null or btrim(p_html) = '' then
    raise exception 'Official terms content is empty.' using errcode = '22023';
  end if;
  v_digest := encode(sha256(convert_to(p_html, 'UTF8')), 'hex');
  select s.revision, s.sha256 into v_prior_rev, v_prior_hash
    from public.official_terms_snapshots s order by s.revision desc limit 1;
  if v_prior_rev is not null and v_prior_hash = v_digest then
    return v_prior_rev;
  end if;
  v_rev := coalesce(v_prior_rev, 0) + 1;
  insert into public.official_terms_snapshots (revision, source_url, fetched_at, sha256, html)
    values (v_rev, p_source_url, now(), v_digest, p_html);
  return v_rev;
end;
$$;

-- ---------------------------------------------------------------------------------------------
-- Public views: the ONLY thing visitors can read. Each lists the exact columns it exposes.
-- They run with the owner's rights on purpose (security_invoker = false) so visitors never
-- need access to the base tables. Supabase's linter will flag this; it is intentional.
-- ---------------------------------------------------------------------------------------------
create or replace view public.public_offers with (security_invoker = false) as
select
  o.offer_id,
  o.revision,
  o.updated_at,
  o.payload ->> 'name'                      as name,
  o.payload ->> 'category'                  as category,
  o.payload ->> 'description'               as description,
  o.payload ->> 'benefits'                  as benefits,
  o.payload ->> 'eligibility'               as eligibility,
  o.payload ->> 'restrictions'              as restrictions,
  o.payload ->> 'exclusions'                as exclusions,
  o.payload ->> 'terms'                     as terms,
  o.payload ->> 'tc_url'                    as tc_url,
  o.payload ->> 'original_source'           as original_source,
  o.payload ->> 'keywords'                  as keywords,
  o.payload ->> 'calculation_rules'         as calculation_rules,
  o.payload ->> 'notes'                     as notes,
  o.payload ->> 'notice_period'             as notice_period,
  o.payload ->> 'schedule_details'          as schedule_details,
  o.payload ->> 'launch_date'               as launch_date,
  o.payload ->> 'launch_date_evidence'      as launch_date_evidence,
  o.payload ->> 'wallet_activation_date'    as wallet_activation_date,
  o.payload ->> 'wallet_activation_details' as wallet_activation_details,
  coalesce(o.payload ->> 'lifecycle', 'available') as lifecycle
from public.offers o
where coalesce((o.payload ->> 'deleted')::boolean, false) = false
  and coalesce((o.payload ->> 'fictional')::boolean, false) = false;

create or replace view public.public_templates with (security_invoker = false) as
select
  t.template_id,
  t.revision,
  t.payload ->> 'title'    as title,
  t.payload ->> 'category' as category,
  t.payload ->> 'path'     as path,
  t.payload ->> 'source'   as source,
  (t.payload ->> 'start')::integer as start,
  t.payload -> 'blocks'     as blocks,
  t.payload -> 'paragraphs' as paragraphs
from public.gto_templates t
where t.deleted = false;

create or replace view public.public_official_terms with (security_invoker = false) as
select s.revision, s.source_url, s.fetched_at, s.html
from public.official_terms_snapshots s
order by s.revision desc
limit 1;

-- ---------------------------------------------------------------------------------------------
-- Privileges. RLS is the gate; these revokes make a mistake fail loudly instead of silently.
-- ---------------------------------------------------------------------------------------------
revoke all on all tables    in schema public from anon;
revoke all on all sequences in schema public from anon;
revoke all on all functions in schema public from public, anon;

grant select on public.public_offers, public.public_templates, public.public_official_terms to anon, authenticated;

grant execute on function public.is_admin()                                   to authenticated;
grant execute on function public.admin_save_offer(jsonb, integer, text)       to authenticated;
grant execute on function public.admin_save_template(jsonb, integer, text)    to authenticated;
grant execute on function public.admin_add_terms_snapshot(text, text)         to authenticated;
